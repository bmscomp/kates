package detect

import (
	"fmt"
	"strings"
	"time"

	"github.com/go-pdf/fpdf"
)

// RenderPDF writes the detect report as an A4 PDF document.
func RenderPDF(report *DetectReport, filePath string) error {
	return renderPDFDoc(BuildReportDoc(report)).OutputFileAndClose(filePath)
}

const (
	pdfWidth    = 180.0 // usable width of an A4 page between 15mm margins
	pdfRowH     = 6.0
	pdfLineH    = 5.0
	pdfCellPad  = 3.0
	pdfMinColW  = 14.0
	pdfBottomMm = 15.0
)

type rgb struct{ r, g, b int }

var (
	pdfText      = rgb{60, 60, 60}
	pdfAccent    = rgb{100, 80, 200}
	pdfHeadFill  = rgb{30, 41, 59}
	pdfHeadText  = rgb{196, 181, 253}
	pdfRowFill   = [2]rgb{{248, 250, 252}, {255, 255, 255}}
	pdfStatusRGB = map[Status]rgb{
		StatusOK:      {16, 185, 129},
		StatusWarn:    {245, 158, 11},
		StatusFail:    {239, 68, 68},
		StatusSkipped: {120, 120, 120},
	}
)

// pdfSpellOut spells the marks cp1252 lacks, which tr would turn into "?".
var pdfSpellOut = strings.NewReplacer("≥", ">=", "≤", "<=", "✓", "ok", "✖", "x", "→", "->")

// pdfView draws a ReportDoc. The core fonts are cp1252 and fpdf writes
// strings byte for byte, so every string goes through tr, which maps each
// rune to its cp1252 byte ("?" when it has none): a UTF-8 "≥" or a node
// name with an accent would otherwise come out as mojibake.
type pdfView struct {
	pdf *fpdf.Fpdf
	tr  func(string) string
}

func renderPDFDoc(doc *ReportDoc) *fpdf.Fpdf {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetAutoPageBreak(true, pdfBottomMm)
	pdf.SetMargins(15, 15, 15)
	cp1252 := pdf.UnicodeTranslatorFromDescriptor("")
	v := &pdfView{pdf: pdf, tr: func(s string) string { return cp1252(pdfSpellOut.Replace(s)) }}
	pdf.SetFooterFunc(func() {
		pdf.SetY(-15)
		pdf.SetFont("Helvetica", "I", 8)
		pdf.SetTextColor(120, 120, 120)
		pdf.CellFormat(0, 10, fmt.Sprintf("Page %d | Generated by kates detect", pdf.PageNo()), "", 0, "C", false, 0, "")
	})
	pdf.SetHeaderFunc(func() {
		if pdf.PageNo() > 1 {
			pdf.SetFont("Helvetica", "B", 8)
			v.color(pdfAccent)
			pdf.CellFormat(0, 8, v.tr(doc.Title), "B", 0, "L", false, 0, "")
			pdf.Ln(8)
		}
	})
	pdf.AddPage()
	v.title(doc)
	for _, s := range doc.Sections {
		v.section(s)
	}
	return pdf
}

func (v *pdfView) color(c rgb) { v.pdf.SetTextColor(c.r, c.g, c.b) }
func (v *pdfView) fill(c rgb)  { v.pdf.SetFillColor(c.r, c.g, c.b) }

// statusColor is the text colour for a status; neutral text is grey.
func (v *pdfView) statusColor(st Status) {
	c, ok := pdfStatusRGB[st]
	if !ok {
		c = pdfText
	}
	v.color(c)
}

// para writes wrapping text in the current font.
func (v *pdfView) para(text string) {
	v.pdf.MultiCell(0, pdfLineH, v.tr(text), "", "L", false)
}

func (v *pdfView) title(doc *ReportDoc) {
	pdf := v.pdf
	pdf.SetFont("Helvetica", "B", 22)
	v.color(pdfAccent)
	pdf.CellFormat(0, 12, v.tr(doc.Title), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 9)
	v.color(rgb{120, 120, 120})
	meta := "Date: " + doc.GeneratedAt.Format(time.RFC3339)
	for _, f := range doc.Meta {
		meta += "  |  " + f.Label + ": " + f.Value
	}
	v.para(meta)
	pdf.Ln(4)

	c := pdfStatusRGB[doc.Verdict.Status]
	v.fill(c)
	pdf.SetTextColor(255, 255, 255)
	pdf.SetFont("Helvetica", "B", 14)
	pdf.CellFormat(pdfWidth, 10, v.tr(doc.Verdict.Label), "1", 1, "C", true, 0, "")
	pdf.Ln(1)
	pdf.SetFont("Helvetica", "", 9)
	v.color(pdfText)
	v.para(doc.Verdict.Summary)
	pdf.Ln(4)
}

func (v *pdfView) section(s Section) {
	pdf := v.pdf
	pdf.Ln(2)
	pdf.SetFont("Helvetica", "B", 12)
	pdf.SetTextColor(15, 23, 42)
	title := s.Title
	if s.Status != StatusNone {
		title += "  [" + string(s.Status) + "]"
	}
	pdf.CellFormat(0, 8, v.tr(title), "", 1, "L", false, 0, "")
	pdf.SetDrawColor(pdfAccent.r, pdfAccent.g, pdfAccent.b)
	pdf.SetLineWidth(0.4)
	x, y := pdf.GetX(), pdf.GetY()
	pdf.Line(x, y-1, x+pdfWidth, y-1)
	pdf.Ln(2)

	pdf.SetFont("Helvetica", "", 9)
	for _, p := range s.Paragraphs {
		v.statusColor(s.Status)
		v.para(p)
	}
	for _, f := range s.Facts {
		v.statusColor(f.Status)
		v.para("- " + f.Label + ": " + f.Value)
	}
	v.color(pdfText)
	for _, m := range s.Meters {
		v.para(fmt.Sprintf("- %s: %.0f%% (%s)", m.Label, m.Percent, m.Detail))
	}
	for _, t := range s.Tables {
		pdf.Ln(1)
		v.table(t)
	}
	v.code(s.Code)
	pdf.SetFont("Helvetica", "I", 8)
	for _, n := range s.Notes {
		v.para(n)
	}
	for _, h := range s.Hints {
		v.hint(h)
	}
	pdf.Ln(3)
}

func (v *pdfView) code(lines []string) {
	if len(lines) == 0 {
		return
	}
	v.pdf.SetFont("Courier", "", 7.5)
	v.color(rgb{120, 40, 40})
	for _, l := range lines {
		v.para(l)
	}
	v.color(pdfText)
}

// columnWidths shares the page width between a table's columns by the
// width of their widest text, each at least pdfMinColW.
func (v *pdfView) columnWidths(t Table) []float64 {
	v.pdf.SetFont("Helvetica", "B", 8)
	widths := make([]float64, len(t.Headers))
	for i, h := range t.Headers {
		widths[i] = v.pdf.GetStringWidth(v.tr(h)) + pdfCellPad
	}
	v.pdf.SetFont("Helvetica", "", 8)
	for _, row := range t.Rows {
		for i, c := range row {
			if i < len(widths) {
				widths[i] = max(widths[i], v.pdf.GetStringWidth(v.tr(c.Text))+pdfCellPad)
			}
		}
	}
	total := 0.0
	for _, w := range widths {
		total += w
	}
	sum := 0.0
	for i := range widths {
		widths[i] = max(widths[i]*pdfWidth/total, pdfMinColW)
		sum += widths[i]
	}
	// The minimum can push the row past the margin; shrink it back.
	for i := range widths {
		widths[i] *= pdfWidth / sum
	}
	return widths
}

// fit cuts text, by runes, until it fits a cell of width w.
func (v *pdfView) fit(text string, w float64) string {
	n := len([]rune(text))
	for n > 4 && v.pdf.GetStringWidth(v.tr(text)) > w-1 {
		n--
		text = truncateRunes(text, n)
	}
	return v.tr(text)
}

func (v *pdfView) table(t Table) {
	pdf := v.pdf
	widths := v.columnWidths(t)
	pdf.SetFont("Helvetica", "B", 8)
	v.fill(pdfHeadFill)
	v.color(pdfHeadText)
	for i, h := range t.Headers {
		pdf.CellFormat(widths[i], pdfRowH, v.fit(h, widths[i]), "1", 0, "L", true, 0, "")
	}
	pdf.Ln(-1)
	_, pageH := pdf.GetPageSize()
	for r, row := range t.Rows {
		// A row is drawn cell by cell: break the page before it rather
		// than in its middle.
		if pdf.GetY()+pdfRowH > pageH-pdfBottomMm {
			pdf.AddPage()
		}
		v.fill(pdfRowFill[r%2])
		for i, c := range row {
			if i >= len(widths) {
				break
			}
			style := ""
			if t.Matrix && i == 0 {
				style = "B"
			}
			pdf.SetFont("Helvetica", style, 8)
			v.statusColor(c.Status)
			pdf.CellFormat(widths[i], pdfRowH, v.fit(c.Text, widths[i]), "1", 0, "L", true, 0, "")
		}
		pdf.Ln(-1)
	}
	v.color(pdfText)
	pdf.SetFont("Helvetica", "", 9)
}

func (v *pdfView) hint(h Hint) {
	pdf := v.pdf
	pdf.Ln(1)
	pdf.SetFont("Helvetica", "B", 9)
	label := map[Status]string{StatusFail: "CRITICAL: ", StatusWarn: "WARNING: "}[h.Status]
	if label == "" {
		label = "INFO: "
	}
	c, ok := pdfStatusRGB[h.Status]
	if !ok {
		c = pdfAccent
	}
	v.color(c)
	v.para(label + h.Title)
	v.color(pdfText)
	if len(h.Commands) > 0 {
		pdf.SetFont("Courier", "", 8)
		v.fill(rgb{240, 240, 240})
		for _, cmd := range h.Commands {
			pdf.MultiCell(pdfWidth, 5.5, v.tr("  "+cmd), "1", "L", true)
		}
	}
	if h.DocURL != "" {
		pdf.SetFont("Helvetica", "", 8.5)
		v.color(pdfAccent)
		pdf.CellFormat(0, 4, v.tr("Documentation: "+h.DocURL), "", 1, "L", false, 0, h.DocURL)
		v.color(pdfText)
	}
}

// truncateRunes cuts s to n runes, the last three of them "..." when it was
// longer. Slicing bytes split a multi-byte character and left the cell with
// a broken one.
func truncateRunes(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	return string(r[:n-3]) + "..."
}
