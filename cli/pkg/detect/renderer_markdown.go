package detect

import (
	"fmt"
	"io"
	"strings"
	"time"
)

// RenderMarkdown writes the full detect report as a markdown document.
func RenderMarkdown(report *DetectReport, w io.Writer) {
	renderMarkdownDoc(BuildReportDoc(report), w)
}

// mdIcon marks a status in Markdown.
var mdIcon = map[Status]string{
	StatusOK:      "✅",
	StatusWarn:    "⚠️",
	StatusFail:    "❌",
	StatusSkipped: "⏭️",
}

// mdEscaper keeps cluster text from turning into markup: a pipe would end a
// table cell, and a <script> node name would be raw HTML on a page that
// renders the file.
var mdEscaper = strings.NewReplacer(
	`\`, `\\`, "|", `\|`, "<", `\<`, ">", `\>`, "*", `\*`, "_", `\_`, "`", "\\`", "\n", " ",
)

func mdText(s string) string { return mdEscaper.Replace(s) }

// mdMark is text with its status icon in front, when it has one.
func mdMark(st Status, text string) string {
	if icon := mdIcon[st]; icon != "" {
		return icon + " " + text
	}
	return text
}

func renderMarkdownDoc(doc *ReportDoc, w io.Writer) {
	p := func(format string, args ...interface{}) {
		fmt.Fprintf(w, format+"\n", args...)
	}
	p("# %s", doc.Title)
	p("")
	p("**Date:** %s  ", doc.GeneratedAt.Format(time.RFC3339))
	meta := make([]string, len(doc.Meta))
	for i, f := range doc.Meta {
		meta[i] = fmt.Sprintf("**%s:** %s", f.Label, mdText(f.Value))
	}
	p("%s", strings.Join(meta, " | "))
	p("")
	p("> %s", mdMark(doc.Verdict.Status, "**"+doc.Verdict.Label+"**: "+doc.Verdict.Summary))
	for _, s := range doc.Sections {
		p("")
		renderMarkdownSection(s, p)
	}
	p("")
	p("---")
	p("*Generated by kates detect*")
}

func renderMarkdownSection(s Section, p func(string, ...interface{})) {
	p("## %s", mdMark(s.Status, s.Title))
	for _, para := range s.Paragraphs {
		p("")
		p("%s", mdText(para))
	}
	if len(s.Facts)+len(s.Meters) > 0 {
		p("")
	}
	for _, f := range s.Facts {
		p("- **%s:** %s", f.Label, mdMark(f.Status, mdText(f.Value)))
	}
	for _, m := range s.Meters {
		p("- **%s:** %.0f%% (%s)", m.Label, m.Percent, m.Detail)
	}
	for _, t := range s.Tables {
		p("")
		renderMarkdownTable(t, p)
	}
	if len(s.Code) > 0 {
		p("")
		p("```")
		for _, line := range s.Code {
			p("%s", strings.ReplaceAll(line, "```", "'''"))
		}
		p("```")
	}
	for _, n := range s.Notes {
		p("")
		p("*%s*", mdText(n))
	}
	for _, h := range s.Hints {
		p("")
		renderMarkdownHint(h, p)
	}
}

func renderMarkdownTable(t Table, p func(string, ...interface{})) {
	head := make([]string, len(t.Headers))
	rule := make([]string, len(t.Headers))
	for i, h := range t.Headers {
		head[i], rule[i] = mdText(h), "---"
	}
	p("| %s |", strings.Join(head, " | "))
	p("|%s|", strings.Join(rule, "|"))
	for _, row := range t.Rows {
		texts := make([]string, len(row))
		for i, c := range row {
			texts[i] = mdMark(c.Status, mdText(c.Text))
			if t.Matrix && i == 0 {
				texts[i] = "**" + texts[i] + "**"
			}
		}
		p("| %s |", strings.Join(texts, " | "))
	}
}

func renderMarkdownHint(h Hint, p func(string, ...interface{})) {
	p("### %s", mdMark(h.Status, mdText(h.Title)))
	if h.Check != "" {
		p("")
		p("Check: %s", mdText(h.Check))
	}
	if len(h.Commands) > 0 {
		p("")
		p("```bash")
		for _, cmd := range h.Commands {
			p("%s", cmd)
		}
		p("```")
	}
	if h.DocURL != "" {
		p("")
		p("[Documentation](%s)", h.DocURL)
	}
}
