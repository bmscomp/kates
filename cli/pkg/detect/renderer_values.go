// RenderValues generates a YAML values file with the default 30% reserve.
func RenderValues(report *DetectReport, clusterName string, w io.Writer) error {
	return RenderValuesWithReserve(report, clusterName, 0.30, w)
}

// RenderValuesWithReserve generates a YAML values file with custom reserve.
func RenderValuesWithReserve(report *DetectReport, clusterName string, reserve float64, w io.Writer) error {
	gen := NewValuesGeneratorWithReserve(report, clusterName, reserve)
	vals := gen.Generate()

	// Write comment header
	zoneNames := make([]string, len(report.Zones))
	for i, z := range report.Zones {
		zoneNames[i] = z.Name
	}
	scNames := make([]string, len(report.Storage))
	for i, sc := range report.Storage {
		scNames[i] = sc.Name
	}

	totalCPU := 0
	totalMem := 0
	for _, n := range report.Nodes {
		totalCPU += n.CPU
		totalMem += n.MemoryGi
	}

	header := fmt.Sprintf(`# Auto-generated by kates detect --generate-values
# Provider: %s | Context: %s
# Date: %s
#
# ── Capacity Analysis ──
# Total cluster:    %d CPU, %d GiB
# Existing usage:   %dm CPU (%d%%), %d GiB
# Available:        %dm CPU, %d GiB
# Kafka budget:     %dm CPU (%d%%), %d GiB (%d%%)
# Reserve:          %d%%
# Weakest zone:     %s (%dm CPU, %dGi mem)
# Profile:          %s
#
# ── Component Distribution ──
# Controllers (×%d): %dm CPU, %s each
# Brokers (×%d):     %dm CPU, %s each
# Storage/broker:    %s
#
# ── Network & DNS ──
# CNI:              %s
# Cluster domain:   %s
# Local DNS suffix: svc.%s
# Pod CIDR:         %s
# Service CIDR:     %s
#
# Zones: %s
# StorageClasses: %s
# Strimzi: deployed=%v | Monitoring: prometheus=%v grafana=%v
# Kyverno=%v

`,
		report.Provider, report.Context,
		time.Now().UTC().Format(time.RFC3339),
		gen.Cap.TotalCPU/1000, gen.Cap.TotalMem,
		gen.Cap.UsedCPU, int(gen.Cap.UtilizationPct*100), gen.Cap.UsedMem,
		gen.Cap.AvailableCPU, gen.Cap.AvailableMem,
		gen.Cap.KafkaCPU, int((1.0-gen.Cap.ReservePct)*100),
		gen.Cap.KafkaMem, int((1.0-gen.Cap.ReservePct)*100),
		int(gen.Cap.ReservePct*100),
		gen.Cap.WeakestZone, gen.Cap.WeakestZoneCPU, gen.Cap.WeakestZoneMem,
		gen.Cap.Profile,
		gen.Cap.ControllerReplicas, gen.Cap.ControllerCPU, gen.Cap.ControllerStorage,
		gen.Cap.BrokerReplicas*max(len(report.Zones), 1), gen.Cap.BrokerCPU, formatMem(gen.Cap.BrokerMem),
		gen.Cap.BrokerStorage,
		report.Network.CNI,
		report.Network.ClusterDomain,
		report.Network.ClusterDomain,
		report.Network.PodCIDR,
		report.Network.ServiceCIDR,
		strings.Join(zoneNames, ", "),
		strings.Join(scNames, ", "),
		report.Strimzi.Running,
		report.Monitoring.PodMonitorCRD, report.Monitoring.GrafanaDeployed,
		report.Admission.Kyverno.Installed,
	)

	if _, err := fmt.Fprint(w, header); err != nil {
		return err
	}

	data, err := yaml.Marshal(vals)
	if err != nil {
		return fmt.Errorf("failed to marshal values: %w", err)
	}

	_, err = w.Write(data)
	return err
}

// RenderValuesFromBase writes the base values file with the detected values
// applied over it, base first: see MergeValuesWithBase.
func RenderValuesFromBase(report *DetectReport, clusterName string, baseData []byte, w io.Writer) error {
	return RenderValuesFromBaseWithReserve(report, clusterName, baseData, 0.30, w)
}

// RenderValuesFromBaseWithReserve is RenderValuesFromBase with a custom
// reserve. The header names every key of the base the detected facts
// overrode, so a reviewer sees what changed without diffing.
func RenderValuesFromBaseWithReserve(report *DetectReport, clusterName string, baseData []byte, reserve float64, w io.Writer) error {
	var base map[string]interface{}
	if err := yaml.Unmarshal(baseData, &base); err != nil {
		return fmt.Errorf("failed to parse base values: %w", err)
	}

	gen := NewValuesGeneratorWithReserve(report, clusterName, reserve)
	vals := gen.Generate()

	// Marshal generated values to map
	genData, err := yaml.Marshal(vals)
	if err != nil {
		return fmt.Errorf("failed to marshal generated values: %w", err)
	}
	var genMap map[string]interface{}
	if err := yaml.Unmarshal(genData, &genMap); err != nil {
		return fmt.Errorf("failed to unmarshal generated values: %w", err)
	}

	merged, overrides := MergeValuesWithBase(base, genMap)

	var header strings.Builder
	fmt.Fprintf(&header, "# Auto-generated by kates detect --generate-values (merged with base)\n# Date: %s\n",
		time.Now().UTC().Format(time.RFC3339))
	if len(overrides) == 0 {
		header.WriteString("# The base set nothing the detected facts contradict; detected values filled only the keys it left unset.\n")
	} else {
		header.WriteString("# Detected facts that replaced a value the base set:\n")
		for _, o := range overrides {
			fmt.Fprintf(&header, "#   %s\n", o)
		}
	}
	header.WriteString("\n")
	if _, err := fmt.Fprint(w, header.String()); err != nil {
		return err
	}

	data, err := yaml.Marshal(merged)
	if err != nil {
		return fmt.Errorf("failed to marshal merged values: %w", err)
	}
	_, err = w.Write(data)
	return err
}

// detectedFacts are the keys the generator wins over a base values file:
// what the cluster is, not what the user chose. Everything else — feature
// toggles, resource sizes, listeners, pools — stands as the base set it, and
// the generated value fills in only where the base is silent.
var detectedFacts = map[string]bool{
	"global.clusterDomain": true,
	"global.storageClass":  true,
}

// MergeValuesWithBase layers gen under base: maps merge recursively, a
// scalar or list the base set is kept (a list is never replaced, a toggle
// never flipped), and only the detectedFacts override the base. The second
// result names each overridden key with both values, sorted.
//
// A base that still carries the 0.4 controllerPools/brokerPools keeps them:
// the chart refuses a release that sets both shapes, so the generated
// nodePools.pools are left out of such a merge.
func MergeValuesWithBase(base, gen map[string]interface{}) (map[string]interface{}, []string) {
	if hasLegacyPools(base) {
		if np, ok := gen["nodePools"].(map[string]interface{}); ok {
			np = cloneMap(np)
			delete(np, "pools")
			gen = cloneMap(gen)
			gen["nodePools"] = np
		}
	}
	var overrides []string
	merged := mergeBaseFirst(base, gen, "", &overrides)
	sort.Strings(overrides)
	return merged, overrides
}

func mergeBaseFirst(base, gen map[string]interface{}, prefix string, overrides *[]string) map[string]interface{} {
	// No size hint: len(base)+len(gen) is a sum of lengths read from user
	// YAML, which code scanning reports as a possible overflow, and the hint
	// buys nothing for maps this small.
	result := make(map[string]interface{})
	for k, v := range base {
		result[k] = v
	}
	for k, v := range gen {
		path := k
		if prefix != "" {
			path = prefix + "." + k
		}
		baseVal, exists := result[k]
		if !exists || baseVal == nil {
			result[k] = v
			continue
		}
		genMap, genIsMap := v.(map[string]interface{})
		baseMap, baseIsMap := baseVal.(map[string]interface{})
		switch {
		case genIsMap && baseIsMap:
			result[k] = mergeBaseFirst(baseMap, genMap, path, overrides)
		case detectedFacts[path] && !reflect.DeepEqual(baseVal, v):
			*overrides = append(*overrides, fmt.Sprintf("%s: %v → %v", path, baseVal, v))
			result[k] = v
		}
	}
	return result
}

func hasLegacyPools(base map[string]interface{}) bool {
	for _, key := range []string{"controllerPools", "brokerPools"} {
		if list, ok := base[key].([]interface{}); ok && len(list) > 0 {
			return true
		}
	}
	return false
}

func cloneMap(m map[string]interface{}) map[string]interface{} {
	out := make(map[string]interface{}, len(m))
	for k, v := range m {
		out[k] = v
	}
	return out
}
